void main() {
  //Operator ! (Logical NOT)
  bool sedangHujan = true;
  print(!sedangHujan);

  //Operator || (Logical OR)
  bool hariLibur = true;
  bool sedangLiburan = false;

  print(hariLibur || sedangLiburan);

  // Operator && (Logical AND)
  bool sedangPanas = true;
  bool minumEs = true;

  print(sedangPanas && minumEs);
}
