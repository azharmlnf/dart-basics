//Switch case Switch dan case adalah control flow yang sejenis dengan if dan else dimana switch case ini digunakan untuk percabangan.

void main() {
  int lantaiSaatIni = 1;
  switch (lantaiSaatIni) {
    case 1:
      print('makan Snack');
      break;
    case 2:
      print('Makan Daging');
      break;
    case 3:
      print('Makan Sayur');
      break;
    case 4:
      print('Bersenang senang');
      break;
    default:
      print('Lantai yang anda Masukkan tidak ada ');
  }
}
